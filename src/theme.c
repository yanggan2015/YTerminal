int theme_count(void) { return (int)(sizeof(g_themes) / sizeof(g_themes[0])); }
Theme *theme_get(int idx) {
    if (idx < 0 || idx >= theme_count()) idx = 0;
    return &g_themes[idx];
}
int theme_default(void) { return 0; }

u32 theme_color_256(Theme *t, int index) {
    if (index < 0) index = 0;
    if (index < 16) return t->ansi[index];
    if (index < 232) {
        static const int steps[6] = {0, 95, 135, 175, 215, 255};
        int i = index - 16;
        int r = steps[(i / 36) % 6];
        int g = steps[(i / 6) % 6];
        int b = steps[i % 6];
        return VT_RGB(r, g, b);
    }
    int gray = 8 + (index - 232) * 10;
    return VT_RGB(gray, gray, gray);
}
